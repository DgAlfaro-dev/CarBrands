using Microsoft.EntityFrameworkCore;
using Microsoft.OpenApi.Models;
using PruebaBackend.Api.Configuration;
using PruebaBackend.Api.Data;

var builder = WebApplication.CreateBuilder(args);

// Add services to the container.
builder.Services.AddControllers();

// ProblemDetails (RFC 7807): unhandled errors respond with JSON carrying type,
// title and status instead of an empty body or an HTML page.
builder.Services.AddProblemDetails();

builder.Services.AddEndpointsApiExplorer();
builder.Services.AddSwaggerGen(options =>
{
    options.SwaggerDoc("v1", new OpenApiInfo
    {
        Title = "API de Marcas de Autos",
        Version = "v1",
        Description = """
            Prueba de conocimiento backend: catálogo **MarcasAutos** sobre PostgreSQL.

            ## Endpoints

            | Método | Ruta | Descripción |
            |---|---|---|
            | GET | `/api/marcas-autos` | Lista las marcas. Acepta **búsqueda por nombre** (`nombre`) y **paginación** (`page`, `pageSize`). |
            | GET | `/api/marcas-autos/{id}` | Devuelve una marca por su id; responde `404` (ProblemDetails) si no existe. |

            ## Búsqueda por nombre

            Añade `?nombre=` a la lista: coincidencia **contenida** y **sin distinguir mayúsculas**.

            ```http
            GET /api/marcas-autos?nombre=toy   → [{"id":1,"nombre":"Toyota"}]
            ```

            ## Paginación

            Añade `?page=` (mínimo 1) y/o `?pageSize=` (1 a 100). Sin esos parámetros
            la respuesta usa `page = 1` y `pageSize = 10`. El listado siempre
            devuelve un objeto paginado con `data`, `currentPage`, `pageSize`,
            `totalItems` y `totalPages`:

            | Campo | Descripción |
            |---|---|
            | `data` | Marcas incluidas en esta página |
            | `currentPage` | Página devuelta |
            | `pageSize` | Máximo de elementos por página (`limitPerPage`) |
            | `totalItems` | Total de resultados después del filtro |
            | `totalPages` | Total de páginas disponibles |

            ```http
            GET /api/marcas-autos?page=2&pageSize=2
            → {"data":[{"id":3,"nombre":"Chevrolet"}],"currentPage":2,"pageSize":2,"totalItems":3,"totalPages":2}
            ```

            Un `page` o `pageSize` fuera de rango responde `400` con `application/problem+json`
            y los detalles en `errors`.
            """
    });

    // The XML file generated by <GenerateDocumentationFile> provides the
    // summary, remarks (usage guide) and parameter docs of every operation.
    var xmlPath = Path.Combine(
        AppContext.BaseDirectory,
        $"{typeof(Program).Assembly.GetName().Name}.xml");
    options.IncludeXmlComments(xmlPath);
});

// The connection string comes from configuration (appsettings.json locally,
// ConnectionStrings__Postgres environment variable in Docker) so credentials
// are never hardcoded in the source code. Providers such as Render supply a
// postgres:// URI, which is normalized to key/value pairs below.
const string PostgresConnectionStringName = "Postgres";
var postgresConnectionString = builder.Configuration.GetConnectionString(PostgresConnectionStringName);

if (string.IsNullOrWhiteSpace(postgresConnectionString))
{
    throw new InvalidOperationException(
        $"Falta la cadena de conexión '{PostgresConnectionStringName}'. " +
        "Defínela en appsettings.json o en la variable de entorno ConnectionStrings__Postgres.");
}

var normalizedPostgresConnectionString =
    PostgresConnectionStringNormalizer.Normalize(postgresConnectionString);

builder.Services.AddDbContext<MarcasAutosDbContext>(options =>
    options.UseNpgsql(normalizedPostgresConnectionString));

var app = builder.Build();

// First in the pipeline: any unhandled exception becomes a status-500
// ProblemDetails response (also recorded in the logs).
app.UseExceptionHandler();

// Configure the HTTP request pipeline.
// Swagger is enabled in every environment: this API is a knowledge test and
// must be explorable (UI + schema) wherever it is deployed.
app.UseSwagger();
app.UseSwaggerUI(options =>
{
    options.SwaggerEndpoint("/swagger/v1/swagger.json", "API de Marcas de Autos v1");
});

app.UseAuthorization();

app.MapControllers();

// Apply pending migrations on startup so `docker compose up` leaves the
// database populated (table + seed) without manual steps.
using (var scope = app.Services.CreateScope())
{
    var dbContext = scope.ServiceProvider.GetRequiredService<MarcasAutosDbContext>();

    // Only migrate on a relational provider (PostgreSQL). Integration tests
    // swap the context for InMemory, which does not support migrations.
    if (dbContext.Database.IsRelational())
    {
        await dbContext.Database.MigrateAsync();
    }
}

app.Run();

// The compiler synthesizes the Program class as internal from top-level
// statements; this partial modifier makes it public so WebApplicationFactory<Program>
// can boot the API in integration tests (pattern documented by
// Microsoft.AspNetCore.Mvc.Testing).
public partial class Program
{
}
